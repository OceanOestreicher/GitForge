/** Substitute numbered placeholders once; missing values remain visible. */
export function addData(message: string, ...data: unknown[]): string {
  return message.replace(/\{(\d+)\}/g, (placeholder, index: string) =>
    Number(index) < data.length ? String(data[Number(index)]) : placeholder
  );
}
